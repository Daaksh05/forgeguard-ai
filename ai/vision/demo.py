def generate_demo_visual_evidence(scenario: str = "all") -> Dict[str, Any]:
    """
    Generate structured demo visual evidence dictionary.
    Supported scenarios: 'normal', 'incipient', 'severe', 'all'
    """
    scenarios_map = {
        "normal": get_demo_evidence_normal(),
        "incipient": get_demo_evidence_incipient(),
        "severe": get_demo_evidence_severe()
    }

    if scenario in scenarios_map:
        return scenarios_map[scenario].to_dict()

    return {
        "machine_id": "PUMP_001",
        "mode": "DEMO",
        "description": "Synthetic visual inspection timeline demonstrating progressive bearing failure.",
        "scenarios": {
            "stage_1_normal": get_demo_evidence_normal().to_dict(),
            "stage_2_incipient": get_demo_evidence_incipient().to_dict(),
            "stage_3_severe": get_demo_evidence_severe().to_dict()
        }
    }


def main():
    parser = argparse.ArgumentParser(
        description="ForgeGuard AI Computer Vision Demo Evidence CLI"
    )
    parser.add_argument(
        "--scenario", "-s",
        choices=["normal", "incipient", "severe", "all"],
        default="all",
        help="Inspection scenario to simulate (default: all)"
    )
    parser.add_argument(
        "--output", "-o",
        default=None,
        help="Path to save output JSON evidence (e.g. results/visual_demo_evidence.json)"
    )
    args = parser.parse_args()

    print("=" * 78)
    print("  FORGEGUARD AI — COMPUTER VISION DEMO EVIDENCE GENERATOR")
    print("  Mode: DEMO / SYNTHETIC SCENARIO (Non-Real Model Inference)")
    print("=" * 78)

    evidence_data = generate_demo_visual_evidence(args.scenario)

    if args.scenario != "all":
        print(f"\n[+] Inspection Report for scenario: '{args.scenario}'")
        print(f"  Machine ID:     {evidence_data.get('machine_id')}")
        print(f"  Image ID:       {evidence_data.get('image_id')}")
        print(f"  Timestamp:      {evidence_data.get('timestamp')}")
        print(f"  Visual Status:  {evidence_data.get('overall_visual_status')}")
        print(f"  Max Severity:   {evidence_data.get('max_severity')}")
        print(f"  Mode:           {evidence_data.get('mode')}")
        print(f"  Summary:        {evidence_data.get('summary')}")
        print("\n  Visual Findings:")
        for idx, f in enumerate(evidence_data.get("findings", []), 1):
            print(f"    {idx}. [{f.get('severity')}] {f.get('defect_type')} (Confidence: {f.get('confidence'):.2f})")
            print(f"       Region:         {f.get('region')}")
            print(f"       Observation:    {f.get('visual_evidence')}")
            print(f"       Interpretation: {f.get('possible_implication')}\n")
    else:
        print("\n[+] Full Visual Degradation Progression Scenarios Generated:")
        for stage_name, stage_data in evidence_data.get("scenarios", {}).items():
            print(f"\n  >> {stage_name.upper()} [{stage_data.get('max_severity')}]:")
            print(f"     Image ID: {stage_data.get('image_id')} | Status: {stage_data.get('overall_visual_status')}")
            print(f"     Summary:  {stage_data.get('summary')}")
            for f in stage_data.get("findings", []):
                print(f"     * {f.get('defect_type')}: {f.get('visual_evidence')}")

    if args.output:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(evidence_data, f, indent=2)
        print(f"\n[+] Demo visual evidence saved to: {out_path.resolve()}")

    print("=" * 78 + "\n")


if __name__ == "__main__":
    main()
