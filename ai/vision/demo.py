def get_demo_evidence_normal(
    machine_id: str = "PUMP_001",
    timestamp: str = "2026-10-04T09:30:00Z"
) -> VisualInspectionReport:
    """
    Generate demo visual evidence for healthy baseline operation (Stage 1).
    """
    finding = VisualEvidence(
        machine_id=machine_id,
        image_id=f"IMG_{machine_id}_BASELINE_001",
        timestamp=timestamp,
        defect_type="NORMAL_OPERATION",
        confidence=0.98,
        severity="NORMAL",
        region=BoundingRegion(x=0.0, y=0.0, width=1.0, height=1.0),
        visual_evidence=(
            "Camera frame shows intact epoxy enamel coating across bearing housing; "
            "labyrinth shaft seal is dry with zero fluid egress; "
            "flexible coupling aligned with zero particulate debris."
        ),
        possible_implication=(
            "Nominal baseline machine appearance; no visual indicators of mechanical "
            "or thermal distress."
        ),
        mode="DEMO"
    )

    return VisualInspectionReport(
        machine_id=machine_id,
        image_id=f"IMG_{machine_id}_BASELINE_001",
        timestamp=timestamp,
        findings=[finding],
        mode="DEMO"
    )


